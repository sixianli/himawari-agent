  stage("complete");
  flush("driver_complete");
  const record = { schema: "himawari-__PKT_LABEL__-service-read.v1", passed, failureCode, runtime, installedSourceDigests: sourceDigests, requestCount: 1, startCount: passed ? 1 : null, tool: "read", modelRequests: 0, paidRequests: 0, assertionInputs: { deadlineMs: 30000, cleanupTimeoutMs: 5000, heartbeatLeaseMs: 1500, heartbeatIntervalMs: 250, maxOutputBytes: 512 * 1024 }, fixture: { path: target, sha256: expectedSha256, bytes: expectedBytes.length, device: String(before.dev), inode: String(before.ino), mode: "0600" }, result: { reason: result.reason, exitCode: result.exitCode, taskStarted: result.taskStarted, taskProcessExited: result.taskProcessExited, stdioClosed: result.stdioClosed, srtReset: result.srtReset, taskTreeCleanup: result.taskTreeCleanup, network: result.network, diagnostic: result.diagnostic ?? null }, proofLimits: "Explicit synthetic probe scope drives installed Pi read via actual JobHost and private SRT worker. It does not use production grants, durable Agent/Worker service admission, production state or a model. Timings include instrumentation overhead." };
